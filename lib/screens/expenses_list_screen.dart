class ExpensesListScreen extends StatefulWidget {
  final GoogleSheetsService sheetsService;
  final String spreadsheetId;

  const ExpensesListScreen({
    super.key,
    required this.sheetsService,
    required this.spreadsheetId,
  });

  @override
  State<ExpensesListScreen> createState() => _ExpensesListScreenState();
}

class _ExpensesListScreenState extends State<ExpensesListScreen> {
  List<Expense> _allExpenses = [];
  List<Expense> _filteredExpenses = [];
  bool _isLoading = false;
  Set<String> _selectedCategories = {};
  bool _selectedOther = false;
  DateTime? _selectedMonth;
  DateTime? _selectedDate;
  DateTime? _startDate;
  DateTime? _endDate;
  String _selectedPaidBy = 'All';
  bool?
  _filterOneTimePurchase; // null = all, true = one-time only, false = recurring only
  String _sortBy = 'date'; // 'date' or 'price'
  bool _sortAscending = false; // false = descending (newest/highest first)
  String _searchQuery = '';
  final TextEditingController _searchController = TextEditingController();
  bool _hasUpdatedCategories = false;

  // Event assignment mode: add/remove expenses from an event
  bool _eventAssignmentMode = false;
  Event? _selectedEvent;
  Set<String> _expenseIdsInEvent = {};
  Set<String> _pendingAdds = {};
  Set<String> _pendingRemoves = {};
  bool _isLoadingEventIds = false;
  bool _isSavingEventAssignments = false;
  final FirebaseDatabaseService _firebaseDb = FirebaseDatabaseService();

  @override
  void initState() {
    super.initState();
    widget.sheetsService.setSpreadsheetId(widget.spreadsheetId);
    _loadExpenses().then((_) {
      // Auto-update categories on first load if needed
      if (!_hasUpdatedCategories && _allExpenses.isNotEmpty) {
        // Check if any expenses need category updates
        final needsUpdate = _allExpenses.any((expense) {
          final newCategory = _mapCategoryToNew(expense.category);
          return newCategory != expense.category;
        });

        if (needsUpdate) {
          _hasUpdatedCategories = true;
          _updateExpenseCategories();
        }
      }
    });
  }

  @override
  void dispose() {
    _searchController.dispose();
    super.dispose();
  }

  Future<void> _loadExpenses() async {
    setState(() => _isLoading = true);
    try {
      final expenses = await widget.sheetsService.getExpenses();
      setState(() {
        _allExpenses = expenses;
        _applyFilters();
      });
    } catch (e) {
      debugPrint('Error loading expenses: $e');
      final errorString = e.toString();

      // Specifically check for 403 Permission Error generated by Google APIs
      if (errorString.contains('403') ||
          errorString.contains('caller does not have permission')) {
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              content: const Text(
                'You do not have permission to access this spreadsheet.',
              ),
              backgroundColor: Colors.red,
              duration: const Duration(seconds: 10),
              action: SnackBarAction(
                label: 'Request Access',
                textColor: Colors.white,
                onPressed: () async {
                  final url = Uri.parse(
                    'https://docs.google.com/spreadsheets/d/${widget.spreadsheetId}/edit',
                  );
                  if (await canLaunchUrl(url)) {
                    await launchUrl(url, mode: LaunchMode.externalApplication);
                  } else {
                    if (context.mounted) {
                      ScaffoldMessenger.of(context).showSnackBar(
                        const SnackBar(
                          content: Text(
                            'Could not open browser for requesting access.',
                          ),
                        ),
                      );
                    }
                  }
                },
              ),
            ),
          );
        }
      } else {
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              content: Text('Error loading expenses: $errorString'),
              backgroundColor: Colors.red,
            ),
          );
        }
      }
    } finally {
      setState(() => _isLoading = false);
    }
  }

  String? _mapCategoryToNew(String? oldCategory) {
    if (oldCategory == null || oldCategory.isEmpty) {
      return null;
    }

    final lowerCategory = oldCategory.toLowerCase();

    // Map to new categories based on keywords
    if (lowerCategory.contains('milk')) {
      return 'Milk';
    } else if (lowerCategory.contains('vegetable')) {
      return 'Vegetables';
    } else if (lowerCategory.contains('petrol')) {
      return 'Petrol';
    } else if (lowerCategory.contains('travel') ||
        lowerCategory.contains('cab') ||
        lowerCategory.contains('auto')) {
      return 'Travel Cab Auto';
    } else if (lowerCategory.contains('clothes') ||
        lowerCategory.contains('fashion')) {
      return 'Clothes - Fashion';
    }

    // Return original if no match
    return oldCategory;
  }

  Future<void> _updateExpenseCategories() async {
    setState(() => _isLoading = true);

    try {
      int updatedCount = 0;

      for (var expense in _allExpenses) {
        final newCategory = _mapCategoryToNew(expense.category);

        // Only update if category changed
        if (newCategory != expense.category) {
          final updatedExpense = Expense(
            id: expense.id,
            label: expense.label,
            price: expense.price,
            category: newCategory,
            note: expense.note,
            expenseDate: expense.expenseDate,
            timestamp: expense.timestamp,
            paidBy: expense.paidBy,
            isOneTimePurchase: expense.isOneTimePurchase,
            addedByEmail: expense.addedByEmail,
          );

          await widget.sheetsService.updateExpense(updatedExpense);
          updatedCount++;
        }
      }

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(
              'Updated $updatedCount expense(s) with new categories',
            ),
            backgroundColor: Colors.green,
            duration: const Duration(seconds: 3),
          ),
        );
      }

      // Reload expenses to reflect changes
      await _loadExpenses();
    } catch (e) {
      debugPrint('Error updating expense categories: $e');
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Error updating categories: ${e.toString()}'),
            backgroundColor: Colors.red,
            duration: const Duration(seconds: 5),
          ),
        );
      }
    } finally {
      setState(() => _isLoading = false);
    }
  }

  void _applyFilters() {
    var filtered = List<Expense>.from(_allExpenses);

    // Category filter - support multiple categories
    if (_selectedCategories.isNotEmpty || _selectedOther) {
      filtered = filtered.where((e) {
        // Check for "Other" category
        if (_selectedOther) {
          final isOther =
              e.category == null ||
              e.category!.isEmpty ||
              !ExpenseCategories.categories.any(
                (cat) => e.category!.toLowerCase().contains(cat.toLowerCase()),
              );
          if (isOther) return true;
        }

        // Check for selected categories
        if (_selectedCategories.isNotEmpty &&
            e.category != null &&
            e.category!.isNotEmpty) {
          // Split category string (may contain multiple categories separated by comma)
          final expenseCategories = e.category!
              .split(',')
              .map((c) => c.trim().toLowerCase())
              .toSet();

          // Check if any selected category matches any expense category
          return _selectedCategories.any((selectedCat) {
            final lowerSelected = selectedCat.toLowerCase();
            return expenseCategories.any(
              (expCat) =>
                  expCat.contains(lowerSelected) ||
                  lowerSelected.contains(expCat),
            );
          });
        }

        return false;
      }).toList();
    }

    // Paid By filter
    if (_selectedPaidBy != 'All') {
      filtered = filtered.where((e) {
        if (_selectedPaidBy == 'Not Specified') {
          return e.paidBy == null || e.paidBy!.isEmpty;
        }
        return e.paidBy == _selectedPaidBy;
      }).toList();
    }

    // Month filter
    if (_selectedMonth != null) {
      filtered = filtered.where((e) {
        return e.expenseDate.year == _selectedMonth!.year &&
            e.expenseDate.month == _selectedMonth!.month;
      }).toList();
    }

    // Date filter
    if (_selectedDate != null) {
      filtered = filtered.where((e) {
        return e.expenseDate.year == _selectedDate!.year &&
            e.expenseDate.month == _selectedDate!.month &&
            e.expenseDate.day == _selectedDate!.day;
      }).toList();
    }

    // Date range filter
    if (_startDate != null || _endDate != null) {
      filtered = filtered.where((e) {
        if (_startDate != null && e.expenseDate.isBefore(_startDate!)) {
          return false;
        }
        if (_endDate != null) {
          final endDateEndOfDay = DateTime(
            _endDate!.year,
            _endDate!.month,
            _endDate!.day,
            23,
            59,
            59,
          );
          if (e.expenseDate.isAfter(endDateEndOfDay)) {
            return false;
          }
        }
        return true;
      }).toList();
    }

    // One Time Purchase filter
    if (_filterOneTimePurchase != null) {
      filtered = filtered.where((e) {
        return e.isOneTimePurchase == _filterOneTimePurchase;
      }).toList();
    }

    // Search filter
    if (_searchQuery.isNotEmpty) {
      final searchWords = _searchQuery
          .toLowerCase()
          .trim()
          .split(' ')
          .where((word) => word.isNotEmpty)
          .toList();
      filtered = filtered.where((e) {
        final label = e.label.toLowerCase();
        final note = (e.note ?? '').toLowerCase();
        final searchText = '$label $note';

        // All search words must be found in label or note
        return searchWords.every((word) => searchText.contains(word));
      }).toList();
    }

    // Sort
    if (_sortBy == 'price') {
      filtered.sort((a, b) {
        final comparison = a.price.compareTo(b.price);
        return _sortAscending ? comparison : -comparison;
      });
    } else {
      // Sort by date (default)
      filtered.sort((a, b) {
        final comparison = a.expenseDate.compareTo(b.expenseDate);
        return _sortAscending ? comparison : -comparison;
      });
    }

    setState(() {
      _filteredExpenses = filtered;
    });
  }

  Future<void> _selectMonth() async {
    final now = DateTime.now();
    final currentYear = _selectedMonth?.year ?? now.year;
    final currentMonth = _selectedMonth?.month ?? now.month;

    int? selectedYear = currentYear;
    int? selectedMonth = currentMonth;

    final result = await showDialog<Map<String, int>>(
      context: context,
      builder: (context) {
        return StatefulBuilder(
          builder: (context, setDialogState) {
            return AlertDialog(
              title: const Text('Select Month & Year'),
              content: SizedBox(
                width: double.maxFinite,
                child: Column(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    // Year selector
                    Row(
                      children: [
                        const Text('Year: '),
                        Expanded(
                          child: DropdownButton<int>(
                            value: selectedYear,
                            isExpanded: true,
                            items:
                                List.generate(
                                  now.year - 1999,
                                  (index) => now.year - index,
                                ).map((year) {
                                  return DropdownMenuItem(
                                    value: year,
                                    child: Text(year.toString()),
                                  );
                                }).toList(),
                            onChanged: (value) {
                              setDialogState(() {
                                selectedYear = value;
                              });
                            },
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 16),
                    // Month grid
                    GridView.builder(
                      shrinkWrap: true,
                      physics: const NeverScrollableScrollPhysics(),
                      gridDelegate:
                          const SliverGridDelegateWithFixedCrossAxisCount(
                            crossAxisCount: 3,
                            childAspectRatio: 2.5,
                            crossAxisSpacing: 8,
                            mainAxisSpacing: 8,
                          ),
                      itemCount: 12,
                      itemBuilder: (context, index) {
                        final month = index + 1;
                        final isSelected = selectedMonth == month;
                        return InkWell(
                          onTap: () {
                            setDialogState(() {
                              selectedMonth = month;
                            });
                          },
                          child: Container(
                            decoration: BoxDecoration(
                              color: isSelected
                                  ? Theme.of(context).colorScheme.primary
                                  : Colors.grey[200],
                              borderRadius: BorderRadius.circular(4),
                            ),
                            alignment: Alignment.center,
                            child: Text(
                              DateFormat('MMM').format(DateTime(2000, month)),
                              style: TextStyle(
                                color: isSelected ? Colors.white : Colors.black,
                                fontWeight: isSelected
                                    ? FontWeight.bold
                                    : FontWeight.normal,
                                fontSize: 12,
                              ),
                            ),
                          ),
                        );
                      },
                    ),
                  ],
                ),
              ),
              actions: [
                TextButton(
                  onPressed: () => Navigator.pop(context),
                  child: const Text('Cancel'),
                ),
                ElevatedButton(
                  onPressed: () {
                    if (selectedYear != null && selectedMonth != null) {
                      Navigator.pop(context, {
                        'year': selectedYear!,
                        'month': selectedMonth!,
                      });
                    }
                  },
                  child: const Text('Select'),
                ),
              ],
            );
          },
        );
      },
    );

    if (result != null) {
      setState(() {
        _selectedMonth = DateTime(result['year']!, result['month']!);
        _selectedDate = null; // Clear date filter when month is selected
      });
      _applyFilters();
    }
  }

  Future<void> _selectDate() async {
    final DateTime? picked = await showDatePicker(
      context: context,
      initialDate: _selectedDate ?? DateTime.now(),
      firstDate: DateTime(2000),
      lastDate: DateTime.now(),
    );
    if (picked != null) {
      setState(() {
        _selectedDate = picked;
        _selectedMonth = null; // Clear month filter when date is selected
      });
      _applyFilters();
    }
  }

  Future<void> _selectDateRange() async {
    final DateTime now = DateTime.now();
    DateTime? startDate = _startDate ?? DateTime(now.year, now.month - 1, 1);
    DateTime? endDate = _endDate ?? now;

    final result = await showDialog<Map<String, DateTime?>>(
      context: context,
      builder: (context) {
        return StatefulBuilder(
          builder: (context, setDialogState) {
            return AlertDialog(
              title: const Text('Select Date Range'),
              content: Column(
                mainAxisSize: MainAxisSize.min,
                children: [
                  Row(
                    children: [
                      const Text('Start Date: '),
                      Expanded(
                        child: OutlinedButton(
                          onPressed: () async {
                            final picked = await showDatePicker(
                              context: context,
                              initialDate: startDate ?? DateTime.now(),
                              firstDate: DateTime(2000),
                              lastDate: endDate ?? DateTime.now(),
                            );
                            if (picked != null) {
                              setDialogState(() {
                                startDate = picked;
                              });
                            }
                          },
                          child: Text(
                            startDate != null
                                ? DateFormat('MMM dd, yyyy').format(startDate!)
                                : 'Select',
