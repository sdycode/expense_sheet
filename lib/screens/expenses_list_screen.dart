          onChanged: _onSearchChanged,
        ),
        actions: [
          IconButton(
            icon: const Icon(Icons.event),
            onPressed: _openEventListDialog,
            tooltip: 'Add expenses to event',
          ),
          if (_eventAssignmentMode)
            IconButton(
