                          expense.category!,
                          style: TextStyle(
                            fontSize: 10,
                            color: Colors.grey[700],
                          ),
                        ),
                      ),
                    ],
                    // Notes - only visible when searching
                    if (isSearching &&
                        expense.note != null &&
                        expense.note!.isNotEmpty) ...[
                      const SizedBox(height: 4),
                      Text(
                        expense.note!,
                        style: TextStyle(fontSize: 11, color: Colors.grey[600]),
                        maxLines: 3,
                        overflow: TextOverflow.ellipsis,
                      ),
                    ],
                  ],
                ),
              ),
              const SizedBox(width: 8),
              // Price and +/- when in event mode
              Row(
                mainAxisSize: MainAxisSize.min,
                children: [
                  if (eventAssignmentMode) ...[
                    IconButton(
                      icon: Icon(
                        Icons.remove_circle_outline,
                        size: 22,
                        color: isInEvent ? Colors.red : Colors.grey,
                      ),
                      onPressed: isInEvent ? onRemoveFromEvent : null,
                      padding: EdgeInsets.zero,
                      constraints: const BoxConstraints(
                        minWidth: 32,
                        minHeight: 32,
                      ),
                    ),
                    const SizedBox(width: 4),
                  ],
                  Text(
                    '₹${expense.price.toStringAsFixed(0)}',
                    style: TextStyle(
                      fontSize: 16,
                      fontWeight: FontWeight.bold,
                      color: Theme.of(context).colorScheme.primary,
                    ),
                  ),
                  if (eventAssignmentMode) ...[
                    const SizedBox(width: 4),
                    IconButton(
                      icon: Icon(
                        Icons.add_circle_outline,
                        size: 22,
                        color: !isInEvent ? Colors.green : Colors.grey,
                      ),
                      onPressed: !isInEvent ? onAddToEvent : null,
                      padding: EdgeInsets.zero,
                      constraints: const BoxConstraints(
                        minWidth: 32,
                        minHeight: 32,
                      ),
                    ),
                  ],
                ],
              ),
            ],
          ),
        ),
      ),
    );
  }

  IconData _getCategoryIcon(String? category) {
    switch (category) {
      case 'Food & Groceries':
        return Icons.restaurant;
      case 'Transportation':
        return Icons.directions_car;
      case 'Utilities':
        return Icons.bolt;
      case 'Shopping':
        return Icons.shopping_bag;
      case 'Entertainment':
        return Icons.movie;
      case 'Healthcare':
        return Icons.medical_services;
      case 'Education':
        return Icons.school;
      case 'Bills & Payments':
        return Icons.receipt;
      case 'Personal Care':
        return Icons.spa;
      case 'Home & Maintenance':
        return Icons.home_repair_service;
      case 'Travel':
        return Icons.flight;
      case 'Gifts & Donations':
        return Icons.card_giftcard;
      default:
        return Icons.category;
    }
  }
