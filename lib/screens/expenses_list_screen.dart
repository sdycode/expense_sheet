    if (result != null) {
      setState(() {
        _startDate = result['startDate'];
        _endDate = result['endDate'];
        _selectedMonth = null; // Clear month filter when date range is selected
        _selectedDate = null; // Clear date filter when date range is selected
      });
      _applyFilters();
    }
  }

  void _clearFilters() {
    setState(() {
      _selectedCategories.clear();
      _selectedOther = false;
      _selectedMonth = null;
      _selectedDate = null;
      _startDate = null;
      _endDate = null;
      _selectedPaidBy = 'All';
      _filterOneTimePurchase = null;
      _sortBy = 'date';
      _sortAscending = false;
      _searchQuery = '';
      _searchController.clear();
    });
    _applyFilters();
  }

  void _onSearchChanged(String query) {
    setState(() {
      _searchQuery = query;
    });
    _applyFilters();
  }

  List<String> _getPaidByOptions() {
    final paidBySet = <String>{};
    for (var expense in _allExpenses) {
      if (expense.paidBy != null && expense.paidBy!.isNotEmpty) {
        paidBySet.add(expense.paidBy!);
      }
    }
    final options = ['All', ...paidBySet.toList()..sort()];
    if (_allExpenses.any((e) => e.paidBy == null || e.paidBy!.isEmpty)) {
      options.add('Not Specified');
    }
    return options;
  }

  double _getTotalAmount() {
    if (_eventAssignmentMode && _selectedEvent != null) {
      return _filteredExpenses
          .where((e) => _isExpenseInEvent(e.id))
          .fold(0.0, (sum, expense) => sum + expense.price);
    }
    return _filteredExpenses.fold(0.0, (sum, expense) => sum + expense.price);
  }

  bool _isExpenseInEvent(String expenseId) {
    final inBase = _expenseIdsInEvent.contains(expenseId);
    final added = _pendingAdds.contains(expenseId);
    final removed = _pendingRemoves.contains(expenseId);
    return (inBase || added) && !removed;
  }

  void _onAddExpenseToEvent(String expenseId) {
    setState(() {
      _pendingRemoves.remove(expenseId);
      _pendingAdds.add(expenseId);
    });
  }

  void _onRemoveExpenseFromEvent(String expenseId) {
    setState(() {
      _pendingAdds.remove(expenseId);
      _pendingRemoves.add(expenseId);
    });
  }

  Future<void> _openEventListDialog() async {
    final spreadsheetId = widget.spreadsheetId;
    if (spreadsheetId.isEmpty) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('No spreadsheet ID'),
            backgroundColor: Colors.orange,
          ),
        );
      }
      return;
    }
    List<Event> events;
    try {
      events = await _firebaseDb.getEvents(spreadsheetId);
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Error loading events: $e'),
            backgroundColor: Colors.red,
          ),
        );
      }
      return;
    }
    if (!mounted) return;
    if (events.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('No events yet. Create events first.'),
          backgroundColor: Colors.orange,
        ),
      );
      return;
    }
    final chosen = await showDialog<Event>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: const Text('Select Event'),
        content: SingleChildScrollView(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: events
                .map(
                  (e) => ListTile(
                    title: Text(e.name),
                    onTap: () => Navigator.pop(ctx, e),
                  ),
                )
                .toList(),
          ),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(ctx),
            child: const Text('Cancel'),
          ),
        ],
      ),
    );
    if (chosen != null) {
      setState(() {
        _selectedEvent = chosen;
        _eventAssignmentMode = true;
        _pendingAdds.clear();
        _pendingRemoves.clear();
      });
      _loadExpenseIdsForSelectedEvent();
    }
  }

  Future<void> _loadExpenseIdsForSelectedEvent() async {
    final spreadsheetId = widget.spreadsheetId;
    final event = _selectedEvent;
    if (spreadsheetId.isEmpty || event == null) return;
    setState(() => _isLoadingEventIds = true);
    try {
      final ids = await _firebaseDb.getExpenseIdsForEvent(
        spreadsheetId,
        event.id,
      );
      if (mounted) {
        setState(() {
          _expenseIdsInEvent = ids.toSet();
          _isLoadingEventIds = false;
        });
      }
    } catch (e) {
      if (mounted) {
        setState(() => _isLoadingEventIds = false);
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Error loading event expenses: $e'),
            backgroundColor: Colors.red,
          ),
        );
      }
    }
  }

  void _exitEventAssignmentMode() {
    setState(() {
      _eventAssignmentMode = false;
      _selectedEvent = null;
      _expenseIdsInEvent = {};
      _pendingAdds = {};
      _pendingRemoves = {};
    });
  }

  Future<void> _saveEventAssignments() async {
    final spreadsheetId = widget.spreadsheetId;
    final event = _selectedEvent;
    if (spreadsheetId.isEmpty || event == null) return;
    final toAdd = _pendingAdds.toList();
    final toRemove = _pendingRemoves.toList();
    if (toAdd.isEmpty && toRemove.isEmpty) {
      if (mounted) {
        ScaffoldMessenger.of(
          context,
        ).showSnackBar(const SnackBar(content: Text('No changes to save')));
      }
      return;
    }
    setState(() => _isSavingEventAssignments = true);
    try {
      for (final expenseId in toAdd) {
        final current = await _firebaseDb.getEventIdsForExpense(
          spreadsheetId,
          expenseId,
        );
        final updated = [...current, event.id].toSet().toList();
        await _firebaseDb.setExpenseEvents(spreadsheetId, expenseId, updated);
      }
      for (final expenseId in toRemove) {
        final current = await _firebaseDb.getEventIdsForExpense(
          spreadsheetId,
          expenseId,
        );
        final updated = current.where((id) => id != event.id).toList();
        await _firebaseDb.setExpenseEvents(spreadsheetId, expenseId, updated);
      }
      if (mounted) {
        setState(() {
          _pendingAdds.clear();
          _pendingRemoves.clear();
          _isSavingEventAssignments = false;
        });
        _loadExpenseIdsForSelectedEvent();
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('Event assignments updated'),
            backgroundColor: Colors.green,
          ),
        );
      }
    } catch (e) {
      if (mounted) {
        setState(() => _isSavingEventAssignments = false);
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Error saving: $e'),
            backgroundColor: Colors.red,
          ),
        );
      }
    }
  }

